import type { AppListing, ChangelogEntry, Column, ColumnType, MigrationOp, Review, TableSchema } from '@/types'
import { applyOpsToSchema } from '@/lib/migrate'
import { daysAgo } from '@/lib/utils'

const id = (): Column => ({ name: 'id', type: 'uuid', pk: true })
const col = (name: string, type: ColumnType, extra: Partial<Column> = {}): Column => ({ name, type, ...extra })
const t = (name: string, description: string, columns: Column[]): TableSchema => ({ name, description, columns: [id(), ...columns] })

const log = (version: string, days: number, notes: string, dataSummary?: string[]): ChangelogEntry => ({
  version,
  date: daysAgo(days),
  notes,
  dataSummary,
})

let reviewCounter = 0
const rv = (authorName: string, authorEmoji: string, rating: number, text: string, days: number, reply?: string): Review => ({
  id: `rev_${++reviewCounter}`,
  authorName,
  authorEmoji,
  rating,
  text,
  date: daysAgo(days),
  reply: reply ? { text: reply, date: daysAgo(Math.max(0, days - 1)) } : undefined,
})

const basicLog = (version: string, days: number): ChangelogEntry[] => {
  const [maj, min] = version.split('.').map(Number)
  return [
    log(version, days, 'Little fixes and polish ✨ Faster on older phones.'),
    log(`${maj}.${Math.max(0, min - 1)}.0`, days + 23, 'New look for the main screen, plus a bunch of bug squashing.'),
    log(`${Math.max(1, maj)}.0.0`, days + 70, 'First release! 🎉'),
  ]
}

